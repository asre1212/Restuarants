import {JSDOM} from 'jsdom';
import {indexedDB} from 'fake-indexeddb';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const dom=new JSDOM(fs.readFileSync(new URL('../index.html',import.meta.url),'utf8'),{url:'http://localhost:8080/restaurant-log/'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,indexedDB});
Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
Object.defineProperty(navigator,'onLine',{value:false});
dom.window.HTMLDialogElement.prototype.showModal=function(){this.open=true};
dom.window.HTMLDialogElement.prototype.close=function(){this.open=false};
globalThis.fetch=async()=>({status:401,ok:false});
const db=await import('../db.js'),local=await db.openDB();
const fixtures=[{id:'old',name:'Old Pocha Place',city:'NYC',cuisine:'Korean-pocha',rating:4,notes:'Old notes',tags:['Visited'],deletedAt:null},{id:'new',name:'New Pocha Place',city:'NYC',cuisine:'Korean / Pocha',rating:null,notes:'New notes',tags:['To try'],deletedAt:null}];
await new Promise((resolve,reject)=>{const tx=local.transaction('restaurants','readwrite');fixtures.forEach(row=>tx.objectStore('restaurants').put(row));tx.oncomplete=resolve;tx.onerror=()=>reject(tx.error);});
await db.setting('category-note:'+JSON.stringify(['NYC','Korean-pocha']),'Favorites from the old section');
await import('../app.js');
const $=id=>document.getElementById(id);
assert.deepEqual([...$('map-cuisine').options].map(o=>o.value),['','Korean / Pocha']);
assert.deepEqual([...$('cuisine-options').children].map(o=>o.value),['Korean / Pocha']);
$('city-filter').value='NYC';$('city-filter').dispatchEvent(new dom.window.Event('change'));
$('map-cuisine').value='Korean / Pocha';$('map-cuisine').dispatchEvent(new dom.window.Event('change'));
await new Promise(r=>setTimeout(r,80));
assert.deepEqual([...document.querySelectorAll('#restaurants .card h3')].map(el=>el.textContent),['Old Pocha Place','New Pocha Place']);
assert.equal(document.querySelectorAll('#restaurants .subcategory').length,1);
assert.equal(document.querySelector('.subcategory > summary').firstChild.textContent,'Pocha');
assert.equal(document.querySelector('.subcategory .category-notes textarea').value,'Favorites from the old section');
assert.equal($('visit-filter').options[0].textContent,'All visits (2)');
for(const original of fixtures)assert.deepEqual((await db.all()).find(r=>r.id===original.id),{...original,cuisine:'Korean / Pocha'});
console.log('PASS: existing Pocha sections become one filter and one section, retaining all entries and notes.');
process.exit(0);
